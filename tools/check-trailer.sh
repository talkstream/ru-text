#!/usr/bin/env bash
# Хук commit-msg: каждый коммит несёт трейлер `Red-test:` — самоаттестацию о том, чем проверена
# работа. В этом репозитории нет ни кода, ни харнесса — корпус проверяют гейты и прогоны
# `/ru-text:ru-check`, поэтому трейлер здесь единственный след проверки в истории.
#
# ⚠ ЗАВЕДЁН 28.08.2026, ПОСЛЕ ТОГО КАК ПРАВИЛО УМЕРЛО МОЛЧА. Замер: последние ШЕСТЬ коммитов
# перед этим трейлера не несли — включая релизы 2.5.0, 2.6.0 и 2.7.0. До `13b13e4` он был в
# каждом. Разница не в дисциплине: в приватном репозитории линии стоит этот же хук через
# `core.hooksPath`, и там трейлер есть везде; здесь hooksPath не был задан вовсе, и правило
# держалось обещанием. Обещание, у которого нет механизма, умирает беззвучно — и заметить это
# можно только замером истории, потому что каждый отдельный коммит выглядит нормальным.
#
# ⚠ Зачем понадобился механизм. До 17.08.2026 правило существовало фразой в плане и держалось
# ничем: замер по двадцати последним коммитам дал двенадцать, которых git трейлером не видит.
# Строка при этом написана во ВСЕХ двадцати — расходятся не дисциплина и небрежность, а два
# разных разбора одного текста.
#
# ⚠ Разбор — как у git, НЕ грепом, и это несущее требование. Многострочное значение без отступа
# продолжения рвёт трейлер-блок: git такой трейлер не видит вовсе, а `grep '^Red-test:'` видит.
# Хук на грепе был бы зелёным ровно там, где сегодня дыра. Проверено тремя коммитами в песочнице:
# однострочный — виден; многострочный без отступа — НЕ виден; многострочный с двумя пробелами
# в начале продолжения — виден.
#
# Установка (в каждом клоне, иначе хук не работает):
#     git config core.hooksPath .githooks
#
# Обход — только осознанный и с причиной в теле коммита:
#     TRAILER_OK="<причина>" git commit …
set -euo pipefail

MSG_FILE="${1:-}"
if [[ -z "$MSG_FILE" || ! -f "$MSG_FILE" ]]; then
  echo "check-trailer: нет файла сообщения (аргумент 1)" >&2
  exit 2
fi

# Осознанный обход: причина обязана быть непустой, иначе это не обход, а тихое отключение.
if [[ -n "${TRAILER_OK:-}" ]]; then
  echo "check-trailer: пропуск по TRAILER_OK — «${TRAILER_OK}»"
  exit 0
fi

# Слияния и фиксапы сообщение не сочиняют: у них его пишет git либо будущий rebase.
first_line=$(head -n1 "$MSG_FILE")
case "$first_line" in
  Merge\ *|Revert\ *|fixup!\ *|squash!\ *)
    echo "check-trailer: служебный коммит («${first_line:0:24}…») — трейлер не требуется"
    exit 0
    ;;
esac

# ⚠ Разбор именно `git interpret-trailers`: это тот же код, которым трейлер читает `git log
# --format='%(trailers:…)'`, то есть хук и последующая проверка истории не разойдутся никогда.
# ⚠ Три состояния, не два, и различает их только сравнение двух разборов.
# `git interpret-trailers --parse` ПЕЧАТАЕТ `Red-test:` даже с пустым значением — то есть
# «трейлер распознан» и «значение есть» это разные факты. Замер: на сообщении с голым
# `Red-test:` разбор даёт строку `Red-test: `, а на многострочном без отступа — пустоту.
parsed=$(git interpret-trailers --parse <"$MSG_FILE" || true)
recognised=$(printf '%s\n' "$parsed" | grep -c '^Red-test:' || true)
value=$(printf '%s\n' "$parsed" | sed -n 's/^Red-test:[[:space:]]*//p' | tr -d '[:space:]')

if [[ -z "$value" ]]; then
  # Причины три, и лечатся они по-разному: блок трейлеров порван (строка есть, git её не видит) ·
  # трейлер распознан, но значение пусто · строки нет вовсе. Одно сообщение на все три отправило
  # бы искать не там.
  if [[ "$recognised" -gt 0 ]]; then
    cat >&2 <<'EOF'
✗ Трейлер «Red-test:» есть, но значение пусто.

Аттестация без содержания — это отсутствие аттестации. Напишите, чем проверена работа:

  Red-test: <путь> — <ожидаемая причина падения до кода>
  Red-test: n/a (<почему теста нет; чем проверено вместо него>)
EOF
  elif grep -q '^Red-test:' "$MSG_FILE"; then
    cat >&2 <<'EOF'
✗ Строка «Red-test:» в сообщении ЕСТЬ, но git не считает её трейлером.

Почти всегда причина одна: многострочное значение без отступа продолжения — вторая и следующие
строки обязаны начинаться с пробела, иначе блок трейлеров рвётся на первой из них.

  Red-test: n/a (первая строка
    продолжение с отступом)

Проверить свой текст: git interpret-trailers --parse <файл-сообщения>
EOF
  else
    cat >&2 <<'EOF'
✗ В сообщении нет трейлера «Red-test:».

TDD в этой линии отменён, поэтому трейлер — единственная самоаттестация о том, чем проверена
работа. Формы две:

  Red-test: <путь> — <ожидаемая причина падения до кода>
  Red-test: n/a (<почему теста нет; чем проверено вместо него>)

Осознанный обход, с причиной в теле коммита:
  TRAILER_OK="<причина>" git commit …
EOF
  fi
  exit 1
fi

echo "check-trailer: трейлер на месте"
