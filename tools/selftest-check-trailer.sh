#!/usr/bin/env bash
# Селф-тест хука трейлера: каждый случай — сообщение коммита и ожидаемый код возврата.
#
# ⚠ Незатестированный хук хуже отсутствующего: он создаёт уверенность, не создавая проверки.
# Отдельно проверяется способность КРАСНЕТЬ — иначе зелёный прогон ничего не значит.
#
# Запуск: bash tools/selftest-check-trailer.sh
set -uo pipefail

HOOK="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/check-trailer.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fail=0
n=0

# Проверка: имя · текст сообщения · ожидаемый код · строка, которая обязана быть в выводе
check() {
  local name="$1" msg="$2" want="$3" needle="${4:-}"
  n=$((n + 1))
  printf '%s' "$msg" >"$TMP/msg"
  local out rc
  out=$(bash "$HOOK" "$TMP/msg" 2>&1)
  rc=$?
  if [[ $rc -ne $want ]]; then
    echo "✗ ${name}: код ${rc}, ожидался ${want}"
    echo "    ${out}"
    fail=$((fail + 1))
    return
  fi
  if [[ -n "$needle" && "$out" != *"$needle"* ]]; then
    echo "✗ ${name}: в выводе нет «${needle}»"
    echo "    ${out}"
    fail=$((fail + 1))
  fi
}

check 'однострочный трейлер' \
  'feat: тема

тело

Red-test: n/a (документ; прогнаны гейты)
' 0 'на месте'

check 'многострочный С отступом продолжения' \
  'feat: тема

тело

Red-test: n/a (первая строка
  продолжение с отступом)
' 0 'на месте'

# ⚠ Несущий случай: строка есть, git трейлером её НЕ видит. Хук на грепе тут был бы зелёным.
check 'многострочный БЕЗ отступа — строка есть, трейлера нет' \
  'feat: тема

тело

Red-test: n/a (первая строка
вторая строка без отступа)
' 1 'не считает её трейлером'

check 'трейлера нет вовсе' \
  'feat: тема

тело без аттестации
' 1 'нет трейлера'

# ⚠ Состояний три, и два последних различает только сравнение разборов: `git
# interpret-trailers --parse` печатает `Red-test:` с пустым значением (трейлер РАСПОЗНАН), но
# ничего не печатает на порванном блоке. Первая редакция хука видела два состояния и на пустое
# значение выдавала совет про отступ продолжения — то есть отправляла чинить не то.
check 'трейлер с пустым значением' \
  'feat: тема

тело

Red-test:
' 1 'значение пусто'

check 'трейлер из одних пробелов' \
  'feat: тема

тело

Red-test:   
' 1 'значение пусто'

# Обход гоняется своим прогоном: ему нужна переменная окружения, а `check` её не передаёт.
n=$((n + 1))
printf 'что угодно без трейлера\n' >"$TMP/msg"
out=$(TRAILER_OK='ручной revert, тело объясняет' bash "$HOOK" "$TMP/msg" 2>&1); rc=$?
if [[ $rc -ne 0 || "$out" != *'пропуск по TRAILER_OK'* ]]; then
  echo "✗ обход с причиной: код ${rc}, вывод «${out}»"
  fail=$((fail + 1))
fi

check 'служебный коммит слияния' \
  'Merge branch main into feature
' 0 'служебный коммит'

check 'fixup без трейлера' \
  'fixup! feat: тема
' 0 'служебный коммит'

# Аргументы: без файла и с несуществующим — обе ветки исполнимы.
n=$((n + 1))
out=$(bash "$HOOK" 2>&1); rc=$?
if [[ $rc -ne 2 ]]; then
  echo "✗ без аргумента: код ${rc}, ожидался 2"
  fail=$((fail + 1))
fi

n=$((n + 1))
out=$(bash "$HOOK" "$TMP/нет-такого" 2>&1); rc=$?
if [[ $rc -ne 2 ]]; then
  echo "✗ несуществующий файл: код ${rc}, ожидался 2"
  fail=$((fail + 1))
fi

echo "случаев: ${n} · провалов: ${fail}"
[[ $fail -eq 0 ]] || exit 1
